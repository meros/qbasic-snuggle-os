//! The program: the kernel files and the apps' files joined into one QBasic
//! source, with the optional parts of the kernel that the apps ask for.
//!
//! The kernel is `os/kernel/*.bas`, joined in the order of the file names. A part
//! is a region between `'@if <name>` and `'@endif`, with an `'@else` of stubs for
//! what the core calls. An app is one file in `os/apps` that starts with a
//! manifest line:
//!
//! ```text
//! '@app id=2 name=Clock start=ClockStart timer=ClockTimer uses=controls,timers
//! ```
//!
//! See docs/API.md (generated) for the fields.

use std::fs;
use std::path::{Path, PathBuf};

/// The optional parts of the kernel and what each needs.
pub const COMPONENTS: &[(&str, &[&str])] = &[
    ("timers", &[]),
    ("immediate", &[]),
    ("dirty", &[]),
    ("blocks", &[]),
    ("controls", &[]),
    ("widgets", &["controls"]),
    ("icons", &[]),
    ("notice", &[]),
];

/// The parts every program has.
pub const DEFAULT: &[&str] = &["icons", "notice"];

pub const HEADER: &str = "'SNUGGLE OS: generated by `snuggle build` from os/kernel/*.bas and os/apps/*.bas.\n'Edit those, not this file.\n";

#[derive(Debug, Clone)]
pub struct App {
    pub id: u32,
    pub name: String,
    pub boot: bool,
    pub opaque: bool,
    pub uses: Vec<String>,
    pub start: String,
    pub event: Option<String>,
    pub timer: Option<String>,
    pub paint: Option<String>,
    pub key: Option<String>,
    pub file: String,
    pub body: String,
}

/// What a build should contain beyond the defaults.
#[derive(Debug, Default, Clone)]
pub struct Selection {
    /// Only these apps (file stems); `None` for all of `os/apps`.
    pub only: Option<Vec<String>>,
    /// Also look in `tests/qbasic/fixtures` (test apps, not part of the program).
    pub fixtures: bool,
    /// Parts that no app asks for.
    pub components: Vec<String>,
}

fn is_word_end(c: Option<char>) -> bool {
    !matches!(c, Some(ch) if ch.is_ascii_alphanumeric() || ch == '_')
}

/// `'@if name`, `'@else` or `'@endif` at the start of a line.
fn directive(line: &str) -> Option<(&'static str, String)> {
    for kind in ["if", "else", "endif"] {
        let head = format!("'@{}", kind);
        if let Some(rest) = line.strip_prefix(&head) {
            if is_word_end(rest.chars().next()) {
                let name: String = rest
                    .trim_start()
                    .chars()
                    .take_while(|c| c.is_ascii_alphanumeric() || *c == '_')
                    .collect();
                return Some((kind, name));
            }
        }
    }
    None
}

/// The parts needed: the names, what they require, in dependency order.
pub fn closure(names: &[String]) -> Result<Vec<String>, String> {
    fn add(n: &str, out: &mut Vec<String>) -> Result<(), String> {
        let (_, reqs) = COMPONENTS
            .iter()
            .find(|(c, _)| *c == n)
            .ok_or_else(|| format!("no part called {}", n))?;
        for r in reqs.iter() {
            add(r, out)?;
        }
        if !out.iter().any(|o| o == n) {
            out.push(n.to_string());
        }
        Ok(())
    }
    let mut out = Vec::new();
    for n in names {
        add(n, &mut out)?;
    }
    Ok(out)
}

/// Keep the lines of `'@if` regions of enabled parts (the `'@else` lines of the others).
pub fn preprocess(text: &str, enabled: &[String]) -> Result<String, String> {
    let mut out: Vec<&str> = Vec::new();
    let mut stack: Vec<bool> = Vec::new();
    for line in text.split('\n') {
        match directive(line) {
            Some(("if", name)) => stack.push(enabled.contains(&name)),
            Some(("else", _)) => match stack.last_mut() {
                Some(top) => *top = !*top,
                None => return Err("'@else without '@if".into()),
            },
            Some((_, _)) => {
                if stack.pop().is_none() {
                    return Err("'@endif without '@if".into());
                }
            }
            None => {
                if stack.iter().all(|k| *k) {
                    out.push(line);
                }
            }
        }
    }
    if !stack.is_empty() {
        return Err("an '@if without '@endif".into());
    }
    Ok(out.join("\n"))
}

fn read_lf(path: &Path) -> Result<String, String> {
    fs::read_to_string(path)
        .map(|s| s.replace("\r\n", "\n"))
        .map_err(|e| format!("{}: {}", path.display(), e))
}

/// The kernel source: `os/kernel/*.bas` in file name order.
pub fn kernel(root: &Path) -> Result<String, String> {
    let dir = root.join("os/kernel");
    let mut files: Vec<PathBuf> = fs::read_dir(&dir)
        .map_err(|e| format!("{}: {}", dir.display(), e))?
        .filter_map(|e| e.ok().map(|e| e.path()))
        .filter(|p| p.extension().is_some_and(|x| x == "bas"))
        .collect();
    files.sort();
    let mut out = String::new();
    for f in files {
        out.push_str(&read_lf(&f)?);
        if !out.ends_with('\n') {
            out.push('\n');
        }
        out.push('\n');
    }
    Ok(out)
}

fn parse_app(path: &Path) -> Result<App, String> {
    let text = read_lf(path)?;
    let (first, body) = text.split_once('\n').unwrap_or((&text, ""));
    let file = path.file_name().unwrap().to_string_lossy().to_string();
    let words = first
        .strip_prefix("'@app")
        .ok_or_else(|| format!("{}: no '@app manifest on its first line", file))?;
    let mut app = App {
        id: 0,
        name: String::new(),
        boot: false,
        opaque: false,
        uses: Vec::new(),
        start: String::new(),
        event: None,
        timer: None,
        paint: None,
        key: None,
        file: file.clone(),
        body: body.to_string(),
    };
    for word in words.split_whitespace() {
        let (k, v) = word.split_once('=').unwrap_or((word, ""));
        match k {
            "id" => app.id = v.parse().map_err(|_| format!("{}: bad id", file))?,
            "name" => app.name = v.to_string(),
            "boot" => app.boot = true,
            "opaque" => app.opaque = true,
            "uses" => {
                app.uses = v
                    .split(',')
                    .filter(|u| !u.is_empty())
                    .map(String::from)
                    .collect()
            }
            "start" => app.start = v.to_string(),
            "event" => app.event = Some(v.to_string()),
            "timer" => app.timer = Some(v.to_string()),
            "paint" => app.paint = Some(v.to_string()),
            "key" => app.key = Some(v.to_string()),
            other => return Err(format!("{}: unknown manifest field {}", file, other)),
        }
    }
    for (need, ok) in [
        ("id", app.id != 0),
        ("name", !app.name.is_empty()),
        ("start", !app.start.is_empty()),
    ] {
        if !ok {
            return Err(format!("{}: manifest has no {}=", file, need));
        }
    }
    Ok(app)
}

/// The apps in `os/apps` (and the fixtures), by id.
pub fn apps(root: &Path, fixtures: bool) -> Result<Vec<App>, String> {
    let mut dirs = vec![root.join("os/apps")];
    if fixtures {
        dirs.push(root.join("tests/qbasic/fixtures"));
    }
    let mut found = Vec::new();
    for d in dirs {
        let mut paths: Vec<PathBuf> = fs::read_dir(&d)
            .map_err(|e| format!("{}: {}", d.display(), e))?
            .filter_map(|e| e.ok().map(|e| e.path()))
            .filter(|p| p.extension().is_some_and(|x| x == "bas"))
            .collect();
        paths.sort();
        for p in paths {
            found.push(parse_app(&p)?);
        }
    }
    let mut ids: Vec<u32> = found.iter().map(|a| a.id).collect();
    ids.sort();
    if ids.windows(2).any(|w| w[0] == w[1]) {
        return Err(format!("app ids are not unique: {:?}", ids));
    }
    found.sort_by_key(|a| a.id);
    Ok(found)
}

/// The procedures the kernel calls for the apps, as QBasic has no procedure
/// pointers: a SELECT CASE on the app number for each, then the apps' code.
pub fn generated(found: &[App]) -> String {
    let mut o: Vec<String> = Vec::new();
    let mut p = |s: String| o.push(s);
    for a in found {
        p(format!("CONST AppId{} = {}", a.name, a.id));
    }
    p(String::new());
    p("'Icons for every app, and an instance of each boot app.".into());
    p("SUB AppStartAll".into());
    for a in found {
        p(format!("IconAdd AppId{}, \"{}\"", a.name, a.name));
    }
    for a in found.iter().filter(|a| a.boot) {
        p(format!("AppLaunch AppId{}", a.name));
    }
    p("END SUB".into());
    p(String::new());
    p("SUB AppRun (app)".into());
    p("SELECT CASE app".into());
    for a in found {
        p(format!("CASE AppId{}", a.name));
        p(format!("        {}", a.start));
    }
    p("END SELECT".into());
    p("END SUB".into());
    p(String::new());
    let mut dispatch =
        |comment: &str, head: &str, field: fn(&App) -> &Option<String>, args: &str| {
            p(comment.to_string());
            p(head.to_string());
            for a in found {
                if let Some(proc_) = field(a) {
                    p(format!("CASE AppId{}", a.name));
                    p(format!("        {} {}", proc_, args));
                }
            }
            p("END SELECT".into());
            p("END SUB".into());
            p(String::new());
        };
    dispatch(
        "'A control of window win was clicked or accepted.",
        "SUB AppEvent (win, ctl)\nSELECT CASE HGet(win, WfApp)",
        |a| &a.event,
        "win, ctl",
    );
    dispatch(
        "'A timer of app set with TimerSet ran out.",
        "SUB AppTimer (app, win, tag)\nSELECT CASE app",
        |a| &a.timer,
        "win, tag",
    );
    p("'-1 when the app paints all of its client area (manifest opaque).".into());
    p("FUNCTION AppOpaque (app)".into());
    p("AppOpaque = 0".into());
    p("SELECT CASE app".into());
    for a in found.iter().filter(|a| a.opaque) {
        p(format!("CASE AppId{}", a.name));
        p("        AppOpaque = -1".into());
    }
    p("END SELECT".into());
    p("END FUNCTION".into());
    p(String::new());
    p("'-1 when the app takes the keys of its front window.".into());
    p("FUNCTION AppWantsKeys (app)".into());
    p("AppWantsKeys = 0".into());
    p("SELECT CASE app".into());
    for a in found.iter().filter(|a| a.key.is_some()) {
        p(format!("CASE AppId{}", a.name));
        p("        AppWantsKeys = -1".into());
    }
    p("END SELECT".into());
    p("END FUNCTION".into());
    p(String::new());
    p("'A key for the app of the front window.".into());
    p("SUB AppKey (app, win, k$)".into());
    p("SELECT CASE app".into());
    for a in found {
        if let Some(k) = &a.key {
            p(format!("CASE AppId{}", a.name));
            p(format!("        {} win, k$", k));
        }
    }
    p("END SELECT".into());
    p("END SUB".into());
    p(String::new());
    p("'Run the immediate mode controls of an app's window (UiButton, UiLabel).".into());
    p("SUB AppPaint (app, win)".into());
    p("SELECT CASE app".into());
    for a in found {
        if let Some(pt) = &a.paint {
            p(format!("CASE AppId{}", a.name));
            p(format!("        {} win", pt));
        }
    }
    p("END SELECT".into());
    p("END SUB".into());
    p(String::new());
    for a in found {
        p(format!(
            "'---- app {}: {} (os/apps/{})",
            a.id, a.name, a.file
        ));
        p(a.body.trim_matches('\n').to_string());
        p(String::new());
    }
    let mut s = o.join("\n");
    while s.ends_with('\n') {
        s.pop();
    }
    s.push('\n');
    s
}

/// The program, with LF line ends.
pub fn build_text(root: &Path, sel: &Selection) -> Result<String, String> {
    let kernel = kernel(root)?;
    let hole = "'@@APPS-HERE\n";
    if kernel.matches(hole).count() != 1 {
        return Err("'@@APPS-HERE not found exactly once in os/kernel".into());
    }
    let mut found = apps(root, sel.fixtures)?;
    if let Some(only) = &sel.only {
        found.retain(|a| only.iter().any(|o| *o == a.file.trim_end_matches(".bas")));
    }
    let mut names: Vec<String> = DEFAULT.iter().map(|s| s.to_string()).collect();
    names.extend(sel.components.iter().cloned());
    for a in &found {
        names.extend(a.uses.iter().cloned());
    }
    let enabled = closure(&names)?;
    let text = preprocess(&kernel, &enabled)?;
    Ok(format!(
        "{}{}",
        HEADER,
        text.replace(hole, &generated(&found))
    ))
}

/// The program as the file QBasic runs: CRLF line ends.
pub fn build(root: &Path, sel: &Selection) -> Result<Vec<u8>, String> {
    let text = build_text(root, sel)?;
    if !text.is_ascii() {
        return Err("the program has a character that is not ASCII".into());
    }
    Ok(text.replace('\n', "\r\n").into_bytes())
}

const CALLBACKS: &[(&str, &str, &str)] = &[
    ("start", "`SUB Name ()`", "Make an instance: its windows (AppWindow), controls and timers. Runs for a desktop click and for `boot`."),
    ("event", "`SUB Name (win, ctl)`", "A retained control of the window was clicked, toggled or accepted."),
    ("paint", "`SUB Name (win)`", "Declare immediate mode controls (UiButton, UiLabel). Runs in draw, find and click mode."),
    ("key", "`SUB Name (win, k$)`", "A key while a window of the app is in front. An arrow key is CHR$(0) and a letter (H up, P down, K left, M right)."),
    ("timer", "`SUB Name (win, tag)`", "A timer set with TimerSet ran out."),
];

/// docs/API.md: the manifest, the callbacks and the procedures marked `'@api`.
pub fn api_doc(root: &Path) -> Result<String, String> {
    let kernel = kernel(root)?;
    let lines: Vec<&str> = kernel.split('\n').collect();
    let mut order: Vec<String> = Vec::new();
    let mut sections: Vec<Vec<(String, String)>> = Vec::new();
    for (i, line) in lines.iter().enumerate() {
        let Some(rest) = line.strip_prefix("'@api ") else {
            continue;
        };
        let Some((sec, text)) = rest.split_once("| ") else {
            continue;
        };
        let next = lines.get(i + 1).copied().unwrap_or("");
        let sig = next
            .strip_prefix("SUB ")
            .or_else(|| next.strip_prefix("FUNCTION "))
            .unwrap_or(next);
        let sig = sig.split_whitespace().collect::<Vec<_>>().join(" ");
        let sec = sec.trim().to_string();
        let k = match order.iter().position(|o| *o == sec) {
            Some(k) => k,
            None => {
                order.push(sec);
                sections.push(Vec::new());
                order.len() - 1
            }
        };
        sections[k].push((sig, text.to_string()));
    }
    let mut o: Vec<String> = vec![
        "# Snuggle OS API".into(),
        String::new(),
        "Generated by `snuggle docs` from `os/kernel` (the `'@api` lines). Do not edit by hand.".into(),
        "How the pieces fit: docs/ARCHITECTURE.md.".into(),
        String::new(),
        "## App module".into(),
        String::new(),
        "An app is one file in `os/apps/` that starts with a manifest line:".into(),
        String::new(),
        "```".into(),
        "'@app id=2 name=Clock start=ClockStart timer=ClockTimer uses=controls,timers".into(),
        "```".into(),
        String::new(),
        "| Field | Meaning |".into(),
        "| --- | --- |".into(),
        "| `id` | app number, unique; the builder adds `CONST AppId<Name>` |".into(),
        "| `name` | label of the desktop icon |".into(),
        "| `boot` | start one instance when the desktop starts |".into(),
        "| `uses` | the parts of the kernel the app needs (below); what they require comes with them |".into(),
        "| `opaque` | the paint procedure paints all of the client area, so the kernel skips the white fill under it |".into(),
        "| `start`, `event`, `paint`, `key`, `timer` | the name of a callback procedure (below) |".into(),
        String::new(),
        "## Parts of the kernel".into(),
        String::new(),
        "| Part | Needs | In the program by default |".into(),
        "| --- | --- | --- |".into(),
    ];
    for (name, reqs) in COMPONENTS {
        o.push(format!(
            "| `{}` | {} | {} |",
            name,
            if reqs.is_empty() {
                String::from("")
            } else {
                reqs.iter()
                    .map(|r| format!("`{}`", r))
                    .collect::<Vec<_>>()
                    .join(", ")
            },
            if DEFAULT.contains(name) { "yes" } else { "" }
        ));
    }
    o.push(String::new());
    o.push("## Callbacks".into());
    o.push(String::new());
    o.push("| Manifest field | Signature | When |".into());
    o.push("| --- | --- | --- |".into());
    for (key, sig, text) in CALLBACKS {
        o.push(format!("| `{}=` | {} | {} |", key, sig, text));
    }
    o.push(String::new());
    o.push("Instance state lives in the window's data block (`AppGet`, `AppSet`), so one".into());
    o.push("app can run in several windows. An app that asks for something the heap cannot".into());
    o.push("give gets 0 and `OomFlag`; the kernel then closes the half made instance and".into());
    o.push("shows a notice, so an app need not check each call.".into());
    o.push(String::new());
    for (k, sec) in order.iter().enumerate() {
        o.push(format!("## {}", sec));
        o.push(String::new());
        o.push("| Procedure | What |".into());
        o.push("| --- | --- |".into());
        for (sig, text) in &sections[k] {
            o.push(format!("| `{}` | {} |", sig, text));
        }
        o.push(String::new());
    }
    let mut s = o.join("\n");
    while s.ends_with('\n') {
        s.pop();
    }
    s.push('\n');
    Ok(s)
}
