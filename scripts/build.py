"""Build SNUGGLE.BAS from src/kernel.bas and the app modules in apps/.

    python3 scripts/build.py            write SNUGGLE.BAS (CRLF line endings) and
                                        docs/API.md
    python3 scripts/build.py --check    exit 1 when either is not what the sources
                                        give (the tests run this)

An app module is one .bas file whose first line is its manifest:

    '@app id=1 name=Hello boot start=HelloStart event=HelloEvent timer=HelloTimer

  id     the app number, unique, stored in the windows the app makes
  name   the desktop icon label
  boot   start one instance when the desktop starts
  start  SUB called to make an instance (it makes its windows with AppWindow)
  event  SUB (win, ctl) called for a control event of the app's windows
  timer  SUB (win, tag) called when a TimerSet of the app runs out
  paint  SUB (win) called each time a window of the app is painted and, in
         another mode, to find a click: it declares immediate mode controls
         with UiButton and UiLabel, which cost no heap (see the README)
  key    SUB (win, k$) called for a key when a window of the app is in front
         (the app then gets every key, including Q and R); an arrow key is
         CHR$(0) followed by a letter

The builder adds a constant AppId<Name> for each app, and the procedures the
kernel calls: AppStartAll (icons and boot instances), AppRun, AppEvent and
AppTimer, each a SELECT CASE on the app number (QBasic has no procedure
pointers). The module code goes in at the line '@@APPS-HERE of the kernel.
"""
import pathlib
import re
import sys

root = pathlib.Path(__file__).resolve().parent.parent
HEADER = ("'SNUGGLE OS: generated by scripts/build.py from src/kernel.bas and apps/*.bas.\n"
          "'Edit those, not this file.\n")


def apps():
    found = []
    for path in sorted((root / "apps").glob("*.bas")):
        text = path.read_text().replace("\r\n", "\n")
        first = text.split("\n", 1)[0]
        m = re.match(r"'@app\s+(.*)$", first)
        if not m:
            sys.exit("build: %s has no '@app manifest on its first line" % path.name)
        fields = {"boot": False}
        for word in m.group(1).split():
            k, _, v = word.partition("=")
            fields[k] = v if v else True
        for need in ("id", "name", "start"):
            if need not in fields:
                sys.exit("build: %s: manifest has no %s=" % (path.name, need))
        fields["id"] = int(fields["id"])
        fields["file"] = path.name
        fields["text"] = text
        found.append(fields)
    ids = [a["id"] for a in found]
    if len(set(ids)) != len(ids):
        sys.exit("build: app ids are not unique: %s" % ids)
    return sorted(found, key=lambda a: a["id"])


def generated(found):
    out = []
    for a in found:
        out.append("CONST AppId%s = %d" % (a["name"], a["id"]))
    out.append("")
    out.append("'Icons for every app, and an instance of each boot app.")
    out.append("SUB AppStartAll")
    for a in found:
        out.append('IconAdd AppId%s, "%s"' % (a["name"], a["name"]))
    for a in found:
        if a["boot"]:
            out.append("AppLaunch AppId%s" % a["name"])
    out.append("END SUB")
    out.append("")
    out.append("SUB AppRun (app)")
    out.append("SELECT CASE app")
    for a in found:
        out.append("CASE AppId%s" % a["name"])
        out.append("        %s" % a["start"])
    out.append("END SELECT")
    out.append("END SUB")
    out.append("")
    out.append("'A control of window win was clicked or accepted.")
    out.append("SUB AppEvent (win, ctl)")
    out.append("SELECT CASE HGet(win, WfApp)")
    for a in found:
        if "event" in a:
            out.append("CASE AppId%s" % a["name"])
            out.append("        %s win, ctl" % a["event"])
    out.append("END SELECT")
    out.append("END SUB")
    out.append("")
    out.append("'A timer of app set with TimerSet ran out.")
    out.append("SUB AppTimer (app, win, tag)")
    out.append("SELECT CASE app")
    for a in found:
        if "timer" in a:
            out.append("CASE AppId%s" % a["name"])
            out.append("        %s win, tag" % a["timer"])
    out.append("END SELECT")
    out.append("END SUB")
    out.append("")
    out.append("'-1 when the app takes the keys of its front window.")
    out.append("FUNCTION AppWantsKeys (app)")
    out.append("AppWantsKeys = 0")
    out.append("SELECT CASE app")
    for a in found:
        if "key" in a:
            out.append("CASE AppId%s" % a["name"])
            out.append("        AppWantsKeys = -1")
    out.append("END SELECT")
    out.append("END FUNCTION")
    out.append("")
    out.append("'A key for the app of the front window.")
    out.append("SUB AppKey (app, win, k$)")
    out.append("SELECT CASE app")
    for a in found:
        if "key" in a:
            out.append("CASE AppId%s" % a["name"])
            out.append("        %s win, k$" % a["key"])
    out.append("END SELECT")
    out.append("END SUB")
    out.append("")
    out.append("'Run the immediate mode controls of an app's window (UiButton, UiLabel).")
    out.append("SUB AppPaint (app, win)")
    out.append("SELECT CASE app")
    for a in found:
        if "paint" in a:
            out.append("CASE AppId%s" % a["name"])
            out.append("        %s win" % a["paint"])
    out.append("END SELECT")
    out.append("END SUB")
    out.append("")
    for a in found:
        body = a["text"].split("\n", 1)[1].strip("\n")
        out.append("'---- app %d: %s (apps/%s)" % (a["id"], a["name"], a["file"]))
        out.append(body)
        out.append("")
    return "\n".join(out).rstrip("\n") + "\n"


CALLBACKS = [
    ("start", "`SUB Name ()`", "Make an instance: its windows (AppWindow), controls and timers. Runs for an icon click and for `boot`."),
    ("event", "`SUB Name (win, ctl)`", "A retained control of the window was clicked, toggled or accepted."),
    ("paint", "`SUB Name (win)`", "Declare immediate mode controls (UiButton, UiLabel). Runs in draw, find and click mode."),
    ("key", "`SUB Name (win, k$)`", "A key while a window of the app is in front. An arrow key is CHR$(0) and a letter (H up, P down, K left, M right)."),
    ("timer", "`SUB Name (win, tag)`", "A timer set with TimerSet ran out."),
]


def api_doc():
    """docs/API.md: the manifest, the callbacks and the '@api procedures."""
    lines = (root / "src" / "kernel.bas").read_text().replace("\r\n", "\n").split("\n")
    sections = {}
    order = []
    for i, line in enumerate(lines):
        m = re.match(r"'@api ([^|]+)\| (.*)$", line)
        if not m:
            continue
        sig = re.sub(r"^(SUB|FUNCTION) ", "", lines[i + 1])
        sig = re.sub(r"\s+", " ", sig)
        sec = m.group(1).strip()
        if sec not in sections:
            sections[sec] = []
            order.append(sec)
        sections[sec].append((sig, m.group(2)))
    out = ["# Snuggle OS API", "",
           "Generated by `scripts/build.py` from `src/kernel.bas` (the `'@api` lines).",
           "Do not edit by hand. How the pieces fit: README, \"Apps and the heap\".", "",
           "## App module", "",
           "An app is one file in `apps/` that starts with a manifest line:", "",
           "```", "'@app id=2 name=Clock start=ClockStart timer=ClockTimer", "```", "",
           "| Field | Meaning |", "| --- | --- |",
           "| `id` | app number, unique; the builder adds `CONST AppId<Name>` |",
           "| `name` | label of the desktop icon |",
           "| `boot` | start one instance when the desktop starts |",
           "| `start`, `event`, `paint`, `key`, `timer` | the name of a callback procedure (below) |",
           "", "## Callbacks", "", "| Manifest field | Signature | When |", "| --- | --- | --- |"]
    for key, sig, text in CALLBACKS:
        out.append("| `%s=` | %s | %s |" % (key, sig, text))
    out += ["", "Instance state lives in the window's data block (`AppGet`, `AppSet`), so one",
            "app can run in several windows. An app that asks for something the heap cannot",
            "give gets 0 and `OomFlag`; the kernel then closes the half made instance and",
            "shows a notice, so an app need not check each call.", ""]
    for sec in order:
        out += ["## " + sec, "", "| Procedure | What |", "| --- | --- |"]
        for sig, text in sections[sec]:
            out.append("| `%s` | %s |" % (sig, text))
        out.append("")
    return ("\n".join(out).rstrip("\n") + "\n").encode("ascii")


def build():
    kernel = (root / "src" / "kernel.bas").read_text().replace("\r\n", "\n")
    if kernel.count("'@@APPS-HERE\n") != 1:
        sys.exit("build: '@@APPS-HERE not found exactly once in src/kernel.bas")
    text = HEADER + kernel.replace("'@@APPS-HERE\n", generated(apps()))
    return text.replace("\n", "\r\n").encode("ascii")


if __name__ == "__main__":
    data = build()
    doc = api_doc()
    target = root / "SNUGGLE.BAS"
    doctarget = root / "docs" / "API.md"
    if "--check" in sys.argv:
        for path, want in ((target, data), (doctarget, doc)):
            if not path.exists() or path.read_bytes() != want:
                sys.exit("%s is not up to date: run python3 scripts/build.py" % path.name)
        print("SNUGGLE.BAS and docs/API.md are up to date")
    else:
        target.write_bytes(data)
        doctarget.write_bytes(doc)
        print("wrote %s (%d bytes) and %s" % (target, len(data), doctarget))
