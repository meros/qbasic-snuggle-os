"""Build SNUGGLE.BAS from src/kernel.bas and the app modules in apps/.

    python3 scripts/build.py            write SNUGGLE.BAS (CRLF line endings)
    python3 scripts/build.py --check    exit 1 when SNUGGLE.BAS is not what the
                                        sources give (the tests run this)

An app module is one .bas file whose first line is its manifest:

    '@app id=1 name=Hello boot start=HelloStart event=HelloEvent timer=HelloTimer

  id     the app number, unique, stored in the windows the app makes
  name   the desktop icon label
  boot   start one instance when the desktop starts
  start  SUB called to make an instance (it makes its windows with AppWindow)
  event  SUB (win, ctl) called for a control event of the app's windows
  timer  SUB (win, tag) called when a TimerSet of the app runs out
  paint  SUB (win) called each time a window of the app is painted and, in
         another mode, to find a click: it declares immediate mode controls
         with UiButton and UiLabel, which cost no heap (see the README)

The builder adds a constant AppId<Name> for each app, and the procedures the
kernel calls: AppStartAll (icons and boot instances), AppRun, AppEvent and
AppTimer, each a SELECT CASE on the app number (QBasic has no procedure
pointers). The module code goes in at the line '@@APPS-HERE of the kernel.
"""
import pathlib
import re
import sys

root = pathlib.Path(__file__).resolve().parent.parent
HEADER = ("'SNUGGLE OS: generated by scripts/build.py from src/kernel.bas and apps/*.bas.\n"
          "'Edit those, not this file.\n")


def apps():
    found = []
    for path in sorted((root / "apps").glob("*.bas")):
        text = path.read_text().replace("\r\n", "\n")
        first = text.split("\n", 1)[0]
        m = re.match(r"'@app\s+(.*)$", first)
        if not m:
            sys.exit("build: %s has no '@app manifest on its first line" % path.name)
        fields = {"boot": False}
        for word in m.group(1).split():
            k, _, v = word.partition("=")
            fields[k] = v if v else True
        for need in ("id", "name", "start"):
            if need not in fields:
                sys.exit("build: %s: manifest has no %s=" % (path.name, need))
        fields["id"] = int(fields["id"])
        fields["file"] = path.name
        fields["text"] = text
        found.append(fields)
    ids = [a["id"] for a in found]
    if len(set(ids)) != len(ids):
        sys.exit("build: app ids are not unique: %s" % ids)
    return sorted(found, key=lambda a: a["id"])


def generated(found):
    out = []
    for a in found:
        out.append("CONST AppId%s = %d" % (a["name"], a["id"]))
    out.append("")
    out.append("'Icons for every app, and an instance of each boot app.")
    out.append("SUB AppStartAll")
    for a in found:
        out.append('IconAdd AppId%s, "%s"' % (a["name"], a["name"]))
    for a in found:
        if a["boot"]:
            out.append("AppLaunch AppId%s" % a["name"])
    out.append("END SUB")
    out.append("")
    out.append("SUB AppRun (app)")
    out.append("SELECT CASE app")
    for a in found:
        out.append("CASE AppId%s" % a["name"])
        out.append("        %s" % a["start"])
    out.append("END SELECT")
    out.append("END SUB")
    out.append("")
    out.append("'A control of window win was clicked or accepted.")
    out.append("SUB AppEvent (win, ctl)")
    out.append("SELECT CASE HGet(win, WfApp)")
    for a in found:
        if "event" in a:
            out.append("CASE AppId%s" % a["name"])
            out.append("        %s win, ctl" % a["event"])
    out.append("END SELECT")
    out.append("END SUB")
    out.append("")
    out.append("'A timer of app set with TimerSet ran out.")
    out.append("SUB AppTimer (app, win, tag)")
    out.append("SELECT CASE app")
    for a in found:
        if "timer" in a:
            out.append("CASE AppId%s" % a["name"])
            out.append("        %s win, tag" % a["timer"])
    out.append("END SELECT")
    out.append("END SUB")
    out.append("")
    out.append("'Run the immediate mode controls of an app's window (UiButton, UiLabel).")
    out.append("SUB AppPaint (app, win)")
    out.append("SELECT CASE app")
    for a in found:
        if "paint" in a:
            out.append("CASE AppId%s" % a["name"])
            out.append("        %s win" % a["paint"])
    out.append("END SELECT")
    out.append("END SUB")
    out.append("")
    for a in found:
        body = a["text"].split("\n", 1)[1].strip("\n")
        out.append("'---- app %d: %s (apps/%s)" % (a["id"], a["name"], a["file"]))
        out.append(body)
        out.append("")
    return "\n".join(out).rstrip("\n") + "\n"


def build():
    kernel = (root / "src" / "kernel.bas").read_text().replace("\r\n", "\n")
    if kernel.count("'@@APPS-HERE\n") != 1:
        sys.exit("build: '@@APPS-HERE not found exactly once in src/kernel.bas")
    text = HEADER + kernel.replace("'@@APPS-HERE\n", generated(apps()))
    return text.replace("\n", "\r\n").encode("ascii")


if __name__ == "__main__":
    data = build()
    target = root / "SNUGGLE.BAS"
    if "--check" in sys.argv:
        if not target.exists() or target.read_bytes() != data:
            sys.exit("SNUGGLE.BAS is not up to date: run python3 scripts/build.py")
        print("SNUGGLE.BAS is up to date")
    else:
        target.write_bytes(data)
        print("wrote %s (%d bytes)" % (target, len(data)))
